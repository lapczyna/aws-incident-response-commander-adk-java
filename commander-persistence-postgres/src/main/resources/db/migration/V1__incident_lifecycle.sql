-- -------------------------------------------------------------------------------------
-- Audit log: append-only, enforced by the database
-- -------------------------------------------------------------------------------------
CREATE TABLE audit_events (
    sequence       BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    incident_id    UUID        NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    event_type     TEXT        NOT NULL,
    actor_id       TEXT        NOT NULL REFERENCES actors (id),
    summary        TEXT        NOT NULL,
    details        JSONB       NOT NULL DEFAULT '{}'::jsonb,
    security_relevant BOOLEAN  NOT NULL,
    correlation_id TEXT,
    occurred_at    TIMESTAMPTZ NOT NULL,

    CONSTRAINT audit_summary_present CHECK (length(btrim(summary)) > 0)
);

COMMENT ON COLUMN audit_events.sequence IS
    'Monotonic insert order. Two events can share a millisecond, and a reader still needs to '
    'know which came first, so ordering never relies on occurred_at alone.';

-- Query: the incident audit trail, in order.
CREATE INDEX audit_events_by_incident ON audit_events (incident_id, sequence);

-- Query: the security review subset, across all incidents.
CREATE INDEX audit_events_security
    ON audit_events (occurred_at DESC)
    WHERE security_relevant;

-- An audit log the application can rewrite is not an audit log, and the one moment it would
-- matter is exactly the moment something has gone wrong. A trigger is used rather than a GRANT
-- so the guarantee holds regardless of which role connects, and so it is directly testable.
--
-- The trigger has one deliberate escape hatch. Without it, audit_events could never be removed,
-- and because incidents cascade to their audit entries, no incident could ever be deleted either
-- -- which would make data retention impossible and leave the demo unable to clean up after
-- itself. Rather than weaken the rule, maintenance must announce itself:
--
--     SET LOCAL app.audit_maintenance = 'on';
--
-- The setting is transaction-scoped (SET LOCAL), so it cannot leak into subsequent work on a
-- pooled connection. This is not a security boundary against an attacker who already holds
-- arbitrary SQL access -- nothing at this layer could be. It is a boundary against the
-- application's own ordinary code paths: no repository, service or stray "cleanup" query can
-- rewrite history without stating that intent in a form that shows up in review and in an audit
-- of the code.
CREATE OR REPLACE FUNCTION reject_audit_mutation() RETURNS trigger AS $$
BEGIN
    IF current_setting('app.audit_maintenance', true) = 'on' THEN
        RETURN COALESCE(NEW, OLD);
    END IF;

    RAISE EXCEPTION 'audit_events is append-only; % is not permitted', TG_OP
        USING ERRCODE = 'restrict_violation',
              HINT = 'Retention and cleanup must set app.audit_maintenance for the transaction.';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_events_append_only
    BEFORE UPDATE OR DELETE ON audit_events
    FOR EACH ROW EXECUTE FUNCTION reject_audit_mutation();

COMMENT ON TRIGGER audit_events_append_only ON audit_events IS
    'Enforces append-only at the database. Verified by AuditLogIntegrationTest, which asserts '
    'that UPDATE and DELETE both raise, and that the maintenance escape hatch is explicit.';
